// Pinned Apache-2.0 reference. No installation scripts or runtime downloads.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import ts from "typescript";

const commit = "1742dec56a66e58eef9dda2d2b865823758ca8cd";
const root = new URL("../third_party/meterless-hmem/", import.meta.url);
const modules = [
  "conflictDetection",
  "dreaming",
  "embeddings",
  "index",
  "memoryMining",
  "memoryRetrieval",
  "memoryStore",
  "sleepCycle",
  "trustLedger",
  "types",
];
const files = [
  ["LICENSE", "LICENSE"],
  ...modules.map((name) => [`reference/src/${name}.ts`, `source/${name}.ts`]),
  ["conformance/runner.ts", "conformance/runner.ts"],
  ["conformance/vectors/vectors.json", "conformance/vectors/vectors.json"],
];
const refresh = process.argv.includes("--fetch");
const manifest = {
  repository: "https://github.com/Meterless/Meterless",
  commit,
  license: "Apache-2.0",
  typescript: ts.version,
  files: {},
};
for (const [upstream, local] of files) {
  const target = new URL(local, root);
  await mkdir(new URL(".", target), { recursive: true });
  let bytes;
  if (refresh) {
    const response = await fetch(
      `https://raw.githubusercontent.com/Meterless/Meterless/${commit}/engines/hmem/${upstream}`,
      { signal: AbortSignal.timeout(20000) },
    );
    if (!response.ok)
      throw new Error(`Upstream H-MEM download failed: ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    await writeFile(target, bytes);
  } else bytes = await readFile(target);
  manifest.files[local] = createHash("sha256").update(bytes).digest("hex");
  if (!local.endsWith(".ts")) continue;
  const generated = local.startsWith("source/")
    ? local.replace("source/", "runtime/").replace(/\.ts$/, ".mjs")
    : local.replace(/\.ts$/, ".mjs");
  const output = ts
    .transpileModule(bytes.toString("utf8"), {
      compilerOptions: {
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.ESNext,
      },
      fileName: local,
    })
    .outputText.replace(/from (['"])(\.\/[^'"]+)\.ts\1/g, "from $1$2.mjs$1");
  await mkdir(new URL(".", new URL(generated, root)), { recursive: true });
  await writeFile(
    new URL(generated, root),
    `// GENERATED by scripts/vendor-hmem.mjs from pinned Meterless source.\n${output}`,
  );
  manifest.files[generated] = createHash("sha256")
    .update(await readFile(new URL(generated, root)))
    .digest("hex");
}
await writeFile(
  new URL("manifest.json", root),
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(
  `H-MEM ${commit}: ${Object.keys(manifest.files).length} source/generated artifacts recorded`,
);
